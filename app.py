from flask import Flask, redirect, url_for
from flask_login import LoginManager, current_user
from config import Config
from models import db, User

login_manager = LoginManager()


def create_app():
    app = Flask(__name__)
    app.config.from_object(Config)

    db.init_app(app)
    login_manager.init_app(app)
    login_manager.login_view = "auth.login"
    login_manager.login_message = "Please log in to access this page."
    login_manager.login_message_category = "warning"

    from auth import auth_bp
    from routes.admin import admin_bp
    from routes.manager import manager_bp
    from routes.employee import employee_bp
    from routes.reports import reports_bp
    from routes.jml import jml_bp
    from routes.reviews import reviews_bp

    app.register_blueprint(auth_bp)
    app.register_blueprint(admin_bp, url_prefix="/admin")
    app.register_blueprint(manager_bp, url_prefix="/manager")
    app.register_blueprint(employee_bp, url_prefix="/employee")
    app.register_blueprint(reports_bp, url_prefix="/reports")
    app.register_blueprint(jml_bp, url_prefix="/jml")
    app.register_blueprint(reviews_bp, url_prefix="/reviews")

    with app.app_context():
        db.create_all()

    @app.route("/")
    def index():
        if current_user.is_authenticated:
            return redirect(url_for("auth.dashboard"))
        return redirect(url_for("auth.login"))

    return app


@login_manager.user_loader
def load_user(user_id):
    return db.session.get(User, int(user_id))


if __name__ == "__main__":
    import os
    app = create_app()
    # Use HTTPS if cert files exist (generated by generate_cert.py)
    ssl_context = None
    if os.path.exists("cert.pem") and os.path.exists("key.pem"):
        ssl_context = ("cert.pem", "key.pem")
        print("\n[HTTPS] TLS enabled — open https://127.0.0.1:5000")
        print("[HTTPS] Browser will show a warning for self-signed cert — click Advanced > Proceed\n")
    else:
        print("\n[HTTP] No cert found — running without TLS.")
        print("[HTTP] Run  python generate_cert.py  to enable HTTPS.\n")
    app.run(debug=True, ssl_context=ssl_context)
